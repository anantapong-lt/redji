-- user ชี้ว่าแค่ approved_by (บัญชีแอดมินที่ล็อกอินอยู่) ไม่พอ — ทีมเล็กแบบนี้อาจมีหลายคนใช้
-- บัญชีแอดมิน "ร่วมกัน" ล็อกอินเดียวกัน เลยอยากให้ตอนอนุมัติ "บังคับพิมพ์ชื่อ" คนที่โอนเงินจริงๆ
-- แยกออกมาต่างหาก ไม่ใช่แค่พึ่ง identity ของ session ที่ล็อกอินอยู่เฉยๆ — เพื่อให้รู้ตัวคน
-- รับผิดชอบจริงชัดเจนตอนดูตาราง "จัดการธุรกรรม" (ไม่ต้องเดาว่าใครใช้บัญชีแอดมินนั้นอยู่ตอนนั้น)
--
-- ยังคง approved_by (FK ไป users) ไว้เหมือนเดิมด้วย — เป็น audit trail ระดับ "บัญชีระบบ" ที่กดปุ่ม
-- จริง ส่วน transferred_by_name เป็น "ชื่อคนจริง" ที่พิมพ์เอง คนละชั้นกัน ใช้ประกอบกันได้

ALTER TABLE withdrawals
  ADD COLUMN IF NOT EXISTS transferred_by_name TEXT;
